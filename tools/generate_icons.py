"""Render the editable TouchScene icon spec to Android, SVG and PNG assets.

Run from any directory. --check compares text and decoded PNG pixels without
writing files, so differences in PNG compression across platforms are harmless.
Only Pillow (see requirements-icons.txt) is needed; no SVG or system font tools.
"""

import argparse
import json
import math
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
BRAND = Path("docs/branding")
RES = Path("android/app/src/main/res")
ANDROID_NS = "http://schemas.android.com/apk/res/android"
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def number(value):
    return f"{value:g}"


def path_data(commands):
    return " ".join(c[0] + ",".join(number(v) for v in c[1:]) for c in commands)


def circle_path(point):
    x, y, r = point["cx"], point["cy"], point["radius"]
    return (f"M{number(x-r)},{number(y)} "
            f"a{number(r)},{number(r)} 0,1 0,{number(2*r)},0 "
            f"a{number(r)},{number(r)} 0,1 0,{number(-2*r)},0")


def sampled_contour(spec):
    """Fixed cubic samples shared by the raster renderer and safety checks."""
    points = []
    for command in spec["contour"]:
        if command[0] == "M":
            current = tuple(command[1:])
            points.append(current)
        elif command[0] == "C":
            start = current
            a, b, end = command[1:3], command[3:5], command[5:7]
            for step in range(1, 129):
                t = step / 128
                u = 1 - t
                points.append(tuple(u**3 * start[i] + 3*u*u*t*a[i]
                                    + 3*u*t*t*b[i] + t**3*end[i] for i in (0, 1)))
            current = tuple(end)
        else:
            raise ValueError(f"Unsupported path command: {command[0]}")
    return points


def validate(spec):
    if spec["version"] != 1 or spec["canvas"] != 108:
        raise ValueError("Expected reviewed icon schema v1 and 108dp canvas")
    low_x, low_y, high_x, high_y = spec["safeZone"]
    radius = spec["strokeWidth"] / 2
    for x, y in sampled_contour(spec):
        if not (low_x + radius <= x <= high_x - radius
                and low_y + radius <= y <= high_y - radius):
            raise ValueError("Contour extends outside adaptive safe zone")
        if math.hypot(x - 54, y - 54) + radius > 33:
            raise ValueError("Contour extends outside circular safe zone")
    point = spec["touch"]
    if math.hypot(point["cx"] - 54, point["cy"] - 54) + point["radius"] > 33:
        raise ValueError("Touch point extends outside circular safe zone")


def vector(spec, monochrome=False):
    contour = "#FFFFFF" if monochrome else spec["palette"]["contour"]
    touch = "#FFFFFF" if monochrome else spec["palette"]["touch"]
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icons.py; edit docs/branding/icon-spec.json. -->
<vector xmlns:android="{ANDROID_NS}"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#00000000"
        android:pathData="{path_data(spec['contour'])}"
        android:strokeColor="{contour}" android:strokeWidth="{number(spec['strokeWidth'])}"
        android:strokeLineCap="round" android:strokeLineJoin="round" />
    <path android:fillColor="{touch}"
        android:pathData="{circle_path(spec['touch'])}" />
</vector>
'''


def background_vector(spec):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icons.py. Adaptive background is not pre-masked. -->
<vector xmlns:android="{ANDROID_NS}"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{spec['palette']['background']}" android:pathData="M0,0h108v108h-108z" />
</vector>
'''


def adaptive_xml():
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icons.py. Both launcher entries share this mark. -->
<adaptive-icon xmlns:android="{ANDROID_NS}">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''


def svg(spec):
    palette, point = spec["palette"], spec["touch"]
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated from icon-spec.json. ViewBox is the launcher's central 72dp viewport. -->
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="18 18 72 72"
    role="img" aria-labelledby="title description">
  <title id="title">TouchScene</title>
  <desc id="description">A soft terracotta contour and a brown touch point on warm cream.</desc>
  <rect x="18" y="18" width="72" height="72" fill="{palette['background']}" />
  <path d="{path_data(spec['contour'])}" fill="none" stroke="{palette['contour']}"
      stroke-width="{number(spec['strokeWidth'])}" stroke-linecap="round" stroke-linejoin="round" />
  <circle cx="{number(point['cx'])}" cy="{number(point['cy'])}"
      r="{number(point['radius'])}" fill="{palette['touch']}" />
</svg>
'''


def render(spec, size, shape="square", themed=False, dark=False):
    # Supersampling plus fixed cubic sampling keeps tiny launcher edges smooth.
    scale = 4
    side = size * scale
    viewport = spec["viewport"]
    factor = side / (viewport[2] - viewport[0])
    transform = lambda p: ((p[0] - viewport[0]) * factor, (p[1] - viewport[1]) * factor)
    palette = spec["palette"]
    bg = ("#49332D" if dark else "#F4DCC7") if themed else palette["background"]
    ink = "#FFE4D0" if dark else "#634237"
    image = Image.new("RGBA", (side, side), bg)
    draw = ImageDraw.Draw(image)
    points = [transform(p) for p in sampled_contour(spec)]
    width = round(spec["strokeWidth"] * factor)
    # A continuous offset polygon avoids tiny gaps from hundreds of overlapping
    # short ImageDraw.line joins. Cubics are smooth; no sharp miter joins occur.
    left, right = [], []
    for i, (x, y) in enumerate(points):
        before, after = points[max(0, i-1)], points[min(len(points)-1, i+1)]
        dx, dy = after[0]-before[0], after[1]-before[1]
        length = math.hypot(dx, dy)
        nx, ny = -dy / length * width / 2, dx / length * width / 2
        left.append((x+nx, y+ny))
        right.append((x-nx, y-ny))
    draw.polygon(left + right[::-1], fill=ink if themed else palette["contour"])
    # Explicit round stroke-linecaps match the SVG and Android vector.
    for x, y in (points[0], points[-1]):
        r = width / 2
        draw.ellipse((x-r, y-r, x+r, y+r), fill=ink if themed else palette["contour"])
    point = spec["touch"]
    x, y = transform((point["cx"], point["cy"]))
    radius = point["radius"] * factor
    draw.ellipse((x-radius, y-radius, x+radius, y+radius),
                 fill=ink if themed else palette["touch"])
    if shape != "square":
        alpha = Image.new("L", (side, side), 0)
        mask = ImageDraw.Draw(alpha)
        if shape == "circle":
            mask.ellipse((0, 0, side-1, side-1), fill=255)
        elif shape == "rounded":
            mask.rounded_rectangle((0, 0, side-1, side-1), radius=side*0.22, fill=255)
        else:
            raise ValueError(f"Unknown mask: {shape}")
        image.putalpha(alpha)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def preview(spec):
    image = Image.new("RGBA", (1120, 640), "#F3EAE0")
    draw = ImageDraw.Draw(image)
    title = ImageFont.load_default(size=36)
    label = ImageFont.load_default(size=18)
    small = ImageFont.load_default(size=16)
    draw.text((48, 30), "TouchScene", font=title, fill="#713E32")
    draw.text((49, 78), "Contour + touch / warm, simple, approachable", font=label, fill="#785E51")
    samples = [("Rounded", "rounded", False, False), ("Circle", "circle", False, False),
               ("Themed light*", "circle", True, False), ("Themed dark*", "rounded", True, True)]
    for i, (caption, shape, themed, dark) in enumerate(samples):
        x = 48 + i*268
        image.alpha_composite(render(spec, 220, shape, themed, dark), (x, 134))
        draw.text((x, 373), caption, font=label, fill="#713E32")
    draw.line((48, 422, 1072, 422), fill="#DBC9B8", width=1)
    draw.text((48, 451), "Small-size check", font=label, fill="#713E32")
    for x, size in ((48, 24), (120, 32), (204, 48), (308, 64), (428, 96)):
        image.alpha_composite(render(spec, size, "rounded"), (x, 492))
        draw.text((x, 601), f"{size}px", font=small, fill="#785E51")
    draw.text((632, 472), "One editable geometry source", font=label, fill="#713E32")
    draw.text((632, 507), "No text in the actual app icon", font=small, fill="#785E51")
    draw.text((632, 540), "*Illustrative theme colors only;", font=small, fill="#785E51")
    draw.text((632, 564), "Android chooses the actual tint.", font=small, fill="#785E51")
    return image


def generated_assets(spec):
    outputs = {
        RES / "drawable/ic_launcher_foreground.xml": vector(spec),
        RES / "drawable/ic_launcher_background.xml": background_vector(spec),
        RES / "drawable/ic_launcher_monochrome.xml": vector(spec, monochrome=True),
        RES / "mipmap-anydpi-v26/ic_launcher.xml": adaptive_xml(),
        RES / "mipmap-anydpi-v26/ic_launcher_round.xml": adaptive_xml(),
        BRAND / "touchscene-icon.svg": svg(spec),
        BRAND / "touchscene-icon-1024.png": render(spec, 1024),
        BRAND / "preview.png": preview(spec),
    }
    for density, size in DENSITIES.items():
        outputs[RES / f"mipmap-{density}/ic_launcher.png"] = render(spec, size, "rounded")
        outputs[RES / f"mipmap-{density}/ic_launcher_round.png"] = render(spec, size, "circle")
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated assets without writing")
    args = parser.parse_args()
    spec = json.loads((ROOT / BRAND / "icon-spec.json").read_text(encoding="utf-8"))
    validate(spec)
    outputs = generated_assets(spec)
    mismatches = []
    for relative, content in outputs.items():
        target = ROOT / relative
        if isinstance(content, str):
            ET.fromstring(content)  # Fail generation too if XML/SVG is invalid.
        if args.check:
            same = target.is_file()
            if same and isinstance(content, str):
                same = target.read_text(encoding="utf-8") == content
            elif same:
                with Image.open(target) as saved:
                    same = saved.size == content.size and saved.convert("RGBA").tobytes() == content.tobytes()
            if not same:
                mismatches.append(str(relative))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            if isinstance(content, str):
                target.write_text(content, encoding="utf-8", newline="\n")
            else:
                content.save(target, format="PNG", optimize=False)
    # Deliberately limited to the ten superseded tracked launcher resources.
    legacy = [ROOT / RES / f"mipmap-{density}/{name}.webp"
              for density in DENSITIES for name in ("ic_launcher", "ic_launcher_round")]
    for target in legacy:
        if target.exists():
            if args.check:
                mismatches.append(str(target.relative_to(ROOT)))
            else:
                target.unlink()
    if mismatches:
        print("Stale or missing assets:\n" + "\n".join(mismatches), file=sys.stderr)
        return 1
    print(f"{'Verified' if args.check else 'Generated'} {len(outputs)} icon assets; adaptive safe zone OK.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
